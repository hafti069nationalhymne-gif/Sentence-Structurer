CUR = LIBRARY_DIR / "curation"


# ---------------------------------------------------------------------------- drafts
def draft(kb) -> Path:
    """Draft templates mechanically from fix.templates and examples[].better (the starting point for curation)."""
    out = []
    for r in kb.rules.values():
        if r.scope.routing == "future_watch":
            continue
        for i, text in enumerate(r.fix.templates):
            out.append({"template_id": f"DRAFT-{r.rule_id}-T{i}", "topic": None, "text_en": text,
                        "rule_ids": [r.rule_id], "origin": f"rule:{r.rule_id} fix.templates[{i}]",
                        "audience": r.audience, "product_domains": r.scope.product_domains})
        for i, ex in enumerate(r.examples):
            if ex.better and not ex.better.lower().startswith(("remove", "delete", "state reductions")):
                out.append({"template_id": f"DRAFT-{r.rule_id}-E{i}", "topic": None, "text_en": ex.better,
                            "rule_ids": [r.rule_id], "origin": f"rule:{r.rule_id} examples[{i}].better",
                            "audience": r.audience, "product_domains": r.scope.product_domains})
    p = LIBRARY_DIR / "drafts" / "templates_draft.jsonl"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("".join(json.dumps(d, ensure_ascii=False) + "\n" for d in out), encoding="utf-8")
    print(f"wrote {len(out)} drafts to {p.relative_to(ROOT)}")
    return p


# ---------------------------------------------------------------------------- topic rules
def build_topic_rules(kb, questionnaire) -> dict:
    tmap = json.loads((CUR / "topic_map.json").read_text(encoding="utf-8"))
    general_all = [r.rule_id for r in kb.rules.values() if r.scope.routing == "all"]
    out = {"_doc": "Generated by scripts/build_library.py from library/curation/topic_map.json and "
                   "knowledge/data/claim_object_routing.csv. Candidate rules for a ticket = all routing=all rules "
                   "+ the ECLASS product rules of the segment + the claim-object rules below.",
           "routing_all_rules": general_all, "topics": {}}
    for topic in questionnaire["topics"]:
        m = tmap[topic]
        co_rules = [rid for co in m["claim_objects"] for rid in kb.claim_object_rule_ids(co)]
        co_pack = [rid for co in m.get("claim_objects_if_packaging", []) for rid in kb.claim_object_rule_ids(co)]
        for rid in m["product_rules"] + m["general_rules"] + m["future_rules"] + co_rules + co_pack:
            if rid not in kb.rules:
                raise SystemExit(f"topic_map {topic}: unknown rule {rid}")
        out["topics"][topic] = {
            "claim_objects": m["claim_objects"], "claim_object_rules": co_rules,
            "claim_objects_if_packaging": m.get("claim_objects_if_packaging", []), "claim_object_rules_if_packaging": co_pack,
            "product_rules": m["product_rules"], "general_rules": m["general_rules"], "future_rules": m["future_rules"],
            "titles": {rid: kb.rules[rid].title for rid in dict.fromkeys(co_rules + co_pack + m["product_rules"] + m["general_rules"] + m["future_rules"])},
        }
    return out


# ---------------------------------------------------------------------------- dont say
def build_dont_say(kb, curation, trigger_de, lifts) -> list[dict]:
    examples_de = json.loads((CUR / "examples_de.json").read_text(encoding="utf-8"))
    rows = []

    def base(r):
        return {"rule_id": r.rule_id, "severity": r.severity, "requirement": r.requirement,
                "audience": r.audience, "product_domains": r.scope.product_domains,
                "channels": r.scope.channels, "applies_from": r.scope.applies_from, "routing": r.scope.routing}

    for r in kb.rules.values():
        if r.scope.routing == "future_watch":
            continue  # future law never produces 'Don't say' entries
        if r.severity in ("prohibited", "case_by_case"):
            for ph in r.triggers:
                if ph == "*":
                    continue
                status, lift = trigger_status(curation, r.rule_id, ph)
                de = trigger_de.get(ph, [])
                if status == "banned":
                    reason = f"{r.title}."
                elif status == "conditional":
                    reason = f"{lifts[lift].label} ({r.title.lower()})."
                else:
                    reason = curation["_reasons"]["detector"]
                rows.append({**base(r), "source": "trigger", "phrase_en": ph, "phrase_de": de[0] if de else None,
                             "de_all": de, "status": status, "lift": lift, "match": "phrase",
                             "show": status != "detector", "reason": reason})
        for a in r.fix.avoid:
            qs = QUOTED.findall(a)
            if qs:
                for q in qs:
                    de = trigger_de.get(q, [])
                    rows.append({**base(r), "source": "avoid", "phrase_en": q, "phrase_de": de[0] if de else None,
                                 "de_all": de, "status": "banned", "lift": None, "match": "phrase", "show": True,
                                 "reason": a})
            else:
                rows.append({**base(r), "source": "practice", "phrase_en": a, "phrase_de": None, "de_all": [],
                             "status": "advice", "lift": None, "match": "none", "show": True, "reason": a})
        for i, ex in enumerate(r.examples):
            de = examples_de.get(f"{r.rule_id}#{i}")
            rows.append({**base(r), "source": "example", "phrase_en": ex.claim, "phrase_de": de,
                         "de_all": [de] if de else [], "status": "banned", "lift": None, "match": "sentence",
                         "show": True, "reason": ex.finding or r.title})
    for i, row in enumerate(rows):
        row["id"] = f"DS{i:04d}"
    return rows


# ---------------------------------------------------------------------------- German drafts
def fill_german(templates_path: Path, lib) -> int:
    """Translate empty text_de with the local model, if available. Results are marked de_reviewed=false."""
    missing = [t for t in lib.templates.values() if not t.text_de]
    if not missing:
        return 0
    settings = load_settings()
    from app.ollama_client import make_client
    from app.engine.ai import translate_checked

    client = make_client(settings)
    st = client.status(settings.active_model)
    if not (st.available and st.model_present):
        print(f"German drafts: {len(missing)} templates have no German text and no local model is available ({st.message}).")
        return 0
    rows = read_jsonl(templates_path)
    done = 0
    for row in rows:
        if row.get("text_de"):
            continue
        t = lib.templates[row["template_id"]]
        de = translate_checked(client, settings.active_model, t.text_en, t)
        if de:
            row["text_de"], row["de_reviewed"] = de, False
            done += 1
    templates_path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(f"German drafts: translated {done} of {len(missing)} with {settings.active_model}")
    return done


# ---------------------------------------------------------------------------- reports
def write_coverage(lib, kb, results) -> None:
    cov = library_checks.coverage(lib, kb)
    req = {k: v for k, v in cov.items() if v["required"]}
    unc = [k for k, v in req.items() if not v["covered"]]
    lines = [
        "# Library coverage", "",
        f"Generated by `scripts/build_library.py` on {date.today().isoformat()}.", "",
        f"- Templates: **{len([t for t in lib.templates.values() if t.topic != '_mandatory'])}** recommendation templates "
        f"+ **{len([t for t in lib.templates.values() if t.topic == '_mandatory'])}** mandatory statements "
        f"= {len(lib.templates)} in `templates.jsonl`",
        f"- 'Don't say' entries: {len(lib.dont_say)} ({sum(1 for d in lib.dont_say if d['show'])} shown, "
        f"{sum(1 for d in lib.dont_say if not d['show'])} topic keywords hidden)",
        f"- Rules that must be covered (severity prohibited, case_by_case or evidence; routing eclass or claim_object): **{len(req)}**",
        f"- Covered by at least one template: {sum(1 for v in req.values() if v['templates'])}",
        f"- Covered only by 'Don't say': {sum(1 for v in req.values() if not v['templates'] and v['dont_say'])}",
        f"- **Uncovered: {len(unc)}**" + (f" ({', '.join(unc)})" if unc else ""), "",
        "## Hard checks", "",
        "| Check | Result |", "|---|---|",
    ]
    for name, errs in results.items():
        lines.append(f"| {name} | {'pass' if not errs else f'FAIL ({len(errs)})'} |")
    lines += ["", "## Rules", "", "| Rule | Severity | Routing | Must be covered | Templates | 'Don't say' entries |",
              "|---|---|---|---|---|---|"]
    for rid, v in cov.items():
        lines.append(f"| {rid} | {v['severity']} | {v['routing']} | {'yes' if v['required'] else ''} | "
                     f"{', '.join(v['templates']) or '–'} | {v['dont_say'] or '–'} |")
    (LIBRARY_DIR / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_review_csv(lib) -> None:
    with (LIBRARY_DIR / "REVIEW.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["template_id", "topic", "kind", "specificity", "rule_ids", "text_en", "text_de", "de_reviewed",
                    "approved", "reviewer_comment"])
        for t in lib.templates.values():
            w.writerow([t.template_id, t.topic, t.kind, t.specificity, " ".join(t.rule_ids), t.text_en, t.text_de,
                        "yes" if t.de_reviewed else "no", "yes" if t.approved else "no", ""])


def approve(csv_path: Path) -> None:
    rows = read_jsonl(LIBRARY_DIR / "templates.jsonl")
    by_id = {r["template_id"]: r for r in rows}
    changed = 0
    with csv_path.open(encoding="utf-8-sig", newline="") as f:
        for rec in csv.DictReader(f):
            row = by_id.get(rec["template_id"])
            if not row:
                continue
            yes = lambda v: str(v).strip().lower() in ("yes", "y", "ja", "1", "true", "x")
            new_de = rec.get("text_de", "").strip()
            if new_de and new_de != row.get("text_de") and set(placeholders(new_de)) == set(placeholders(row["text_en"])):
                row["text_de"] = new_de
                changed += 1
            for key in ("de_reviewed", "approved"):
                if yes(rec.get(key, "")) != bool(row.get(key)):
                    row[key] = yes(rec.get(key, ""))
                    changed += 1
            if rec.get("reviewer_comment", "").strip():
                row["notes"] = (row.get("notes", "") + " Reviewer: " + rec["reviewer_comment"].strip()).strip()
    (LIBRARY_DIR / "templates.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(f"approve: {changed} changes imported from {csv_path}")


# ---------------------------------------------------------------------------- main
def build() -> int:
    kb = load_knowledge()
    q = json.loads((LIBRARY_DIR / "questionnaire.json").read_text(encoding="utf-8"))
    curation = load_curation()
    trigger_de = json.loads((CUR / "trigger_de.json").read_text(encoding="utf-8"))
    from app.library import load_lifts
    lifts = load_lifts()

    topic_rules = build_topic_rules(kb, q)
    (LIBRARY_DIR / "topic_rules.json").write_text(json.dumps(topic_rules, ensure_ascii=False, indent=1), encoding="utf-8")
    ds = build_dont_say(kb, curation, trigger_de, lifts)
    (LIBRARY_DIR / "dont_say.jsonl").write_text("".join(json.dumps(d, ensure_ascii=False) + "\n" for d in ds), encoding="utf-8")

    lib = load_library(rules=kb.rules.values())
    fill_german(LIBRARY_DIR / "templates.jsonl", lib)
    lib = load_library(rules=kb.rules.values())

    results = library_checks.run_all(lib, kb)
    write_coverage(lib, kb, results)
    write_review_csv(lib)
    failed = {k: v for k, v in results.items() if v}
    print(f"library: {len(lib.templates)} templates, {len(ds)} 'Don't say' entries, hash {lib.library_hash}")
    for name, errs in results.items():
        print(f"  check {name}: {'pass' if not errs else 'FAIL'}")
        for e in errs[:40]:
            print(f"     - {e}")
        if len(errs) > 40:
            print(f"     ... {len(errs) - 40} more")
    return 1 if failed else 0


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "build"
    if cmd == "draft":
        draft(load_knowledge())
        return 0
    if cmd == "approve":
        approve(Path(argv[2]) if len(argv) > 2 else LIBRARY_DIR / "REVIEW.csv")
        return build()
    if cmd == "build":
        return build()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))

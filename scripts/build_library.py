"""Build and check the ClaimComposer template library.

Usage (from the project folder):
    uv run python scripts/build_library.py            # build + all hard checks (default)
    uv run python scripts/build_library.py draft      # write library/drafts/templates_draft.jsonl from the knowledge base
    uv run python scripts/build_library.py approve library/REVIEW.csv   # import reviewer approvals

`build` writes library/topic_rules.json, library/dont_say.jsonl, library/COVERAGE.md and
library/REVIEW.csv, fills missing German texts with the local model if it is available
(marked de_reviewed=false), and exits with status 1 if any hard check fails.
"""
